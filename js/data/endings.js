/**
 * 取结局文案。
 * @param {number} endingId 1–13
 * @param {string|null} variant engine.VARIANTS 给出的分档键
 */
function getEndingText(endingId, variant = null) {
  const entry = ENDING_TEXTS[endingId];
  if (!entry) throw new Error(`结局 ${endingId} 无文案`);
  if (entry.variants) {
    const v = entry.variants[variant] || entry.variants[Object.keys(entry.variants)[0]];
    return { title: entry.title, subtitle: v.subtitle, body: v.body, orthodoxEffect: !!entry.orthodoxEffect };
  }
  return { title: entry.title, subtitle: entry.subtitle, body: entry.body, orthodoxEffect: !!entry.orthodoxEffect };
}
